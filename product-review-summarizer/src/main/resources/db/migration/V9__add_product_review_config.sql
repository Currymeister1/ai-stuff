-- Convert the seed-managed primary keys to identity columns so JPA can
-- generate technical IDs for rows created by the application.
ALTER TABLE products
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE required_topics
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE product_reviews
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Continue after the IDs that were loaded by the seed migrations.
SELECT setval(
    pg_get_serial_sequence('products', 'id'),
    (SELECT COALESCE(MAX(id), 0) + 1 FROM products),
    false
);

SELECT setval(
    pg_get_serial_sequence('required_topics', 'id'),
    (SELECT COALESCE(MAX(id), 0) + 1 FROM required_topics),
    false
);

SELECT setval(
    pg_get_serial_sequence('product_reviews', 'id'),
    (SELECT COALESCE(MAX(id), 0) + 1 FROM product_reviews),
    false
);

-- Generation settings used by the mock review generator.
CREATE TABLE product_review_config
(
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id           INTEGER NOT NULL UNIQUE REFERENCES products (id),
    age_min              INTEGER NOT NULL,
    age_max              INTEGER NOT NULL,
    review_count         INTEGER NOT NULL,
    general_review_stars INTEGER NOT NULL
);

